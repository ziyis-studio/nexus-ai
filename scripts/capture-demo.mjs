import { chromium, expect } from '@playwright/test'
import { mkdir, rename } from 'node:fs/promises'
import { setTimeout } from 'node:timers/promises'

await mkdir('docs/screenshots', { recursive: true })
await mkdir('docs/demo', { recursive: true })
const browser = await chromium.launch()
const context = await browser.newContext({
  viewport: { width: 1440, height: 1000 },
  recordVideo: { dir: '.local/demo-video', size: { width: 1440, height: 1000 } },
  reducedMotion: 'reduce',
})
const page = await context.newPage()
await page.goto('http://127.0.0.1:3000/login')
await page.getByRole('heading', { name: 'Welcome back.' }).waitFor()
await page.screenshot({ path: 'docs/screenshots/login.png' })
await setTimeout(1200)
await page.getByLabel('Work email').fill('admin@nexus.test')
await page.getByLabel('Password', { exact: true }).fill('Nexus-demo-2026!')
await page.getByRole('button', { name: 'Sign in to workspace' }).click()
await page.getByRole('button', { name: /Acme Corporation/ }).waitFor()
await page.screenshot({ path: 'docs/screenshots/workspaces.png' })
await setTimeout(1200)
await page.getByRole('button', { name: /Acme Corporation/ }).click()
await page.locator('tbody tr').first().waitFor()
await page.screenshot({ path: 'docs/screenshots/tickets.png' })
await setTimeout(1200)
await page
  .getByRole('link', { name: /Delivery delayed for five days/ })
  .first()
  .click()
await page.getByRole('heading', { name: 'Intelligence workspace' }).waitFor()
const analyze = page.getByRole('button', { name: /Analyze with AI|Run a new analysis/ })
await analyze.click()
await page.getByRole('heading', { name: 'Suggested response' }).waitFor({ timeout: 30000 })
await expect(page.getByRole('button', { name: 'Run a new analysis' })).toBeEnabled({ timeout: 30000 })
await page.screenshot({ path: 'docs/screenshots/analysis.png', fullPage: true })
await setTimeout(1500)
await page.getByRole('button', { name: 'Approve draft' }).click()
await page.getByText('Approved for use. No message has been sent.', { exact: false }).waitFor()
await setTimeout(1200)
await page.getByRole('link', { name: 'Knowledge base', exact: true }).click()
await page.getByRole('heading', { name: 'Delivery support procedure' }).waitFor()
await page.screenshot({ path: 'docs/screenshots/knowledge.png' })
await setTimeout(1200)
await page.getByRole('link', { name: 'Execution history', exact: true }).click()
await page.locator('tbody tr').first().waitFor()
await page.screenshot({ path: 'docs/screenshots/history.png' })
await setTimeout(1200)
await page.getByRole('link', { name: /Acme Corporation Workspace/ }).click()
await page.getByRole('button', { name: /Nova Technologies/ }).click()
await page.locator('tbody tr').first().waitFor()
await setTimeout(1200)
await page.setViewportSize({ width: 390, height: 844 })
await page.screenshot({ path: 'docs/screenshots/mobile.png', fullPage: true })
await context.close()
await rename(await page.video().path(), 'docs/demo/product-walkthrough.webm')
await browser.close()
console.log('Captured seven UI views and the synthetic workflow walkthrough.')
